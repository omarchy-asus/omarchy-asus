#!/bin/bash
# bin/compare-build-paths (#258), offline: gh is a stub serving a fake release workflow run
# (its record, its artifacts list and the artifact zip), and the channel's release is a
# directory reached through ci/fetch-release's RELEASE override, signed with a throwaway key
# that stands in for keys/omarchy-asus.asc. The packages are small fabricated ones: the recipe
# foo builds foo and foo-docs, and the release also serves bar, which is never compared.
#   1. the same: identical but for build date, packager, contents and a size within the
#      threshold: exit 0
#   2. differences, exit 1 with the diff: a dropped file, a changed dependency, a changed
#      scriptlet, a changed mode, a size beyond the threshold, a package only the new path
#      builds, a package only the release serves
#   3. a version mismatch: said first, and the rest still compared
#   4. cannot compare, exit 3: the quattro channel, a run off main, a failed run, no artifact
#      for the recipe, an artifact whose digest doesn't match, a release package whose
#      signature doesn't verify
# Usage: [SHOW=1] tests/ci/compare-build-paths.sh [keep]
#   SHOW=1 prints each report; keep leaves the temp dir for inspection
set -u
W=$(cd "$(dirname "$0")/../.." && pwd)
S=$(realpath "$(mktemp -d)")
[[ ${1:-} == keep ]] && echo "state: $S" || trap 'rm -rf "$S"' EXIT
mkdir -p "$S/bin" "$S/ci" "$S/keys" "$S/stubs" "$S/tmp" "$S/fx" "$S/rel"
cp "$W/bin/compare-build-paths" "$W/bin/env.sh" "$S/bin/"
cp "$W/ci/fetch-release" "$W/ci/channel" "$S/ci/"

# a throwaway signing key in place of keys/omarchy-asus.asc
export GNUPGHOME=$S/gnupg
mkdir -m 700 "$GNUPGHOME"
gpg --batch --quiet --passphrase '' --quick-gen-key 'compare-build-paths test' ed25519 sign never 2>/dev/null
gpg --batch --quiet --armor --export >"$S/keys/omarchy-asus.asc"
sign() { rm -f "$1.sig"; gpg --batch --quiet --detach-sign -o "$1.sig" "$1"; }

# gh: answers from $S/fx
cat >"$S/stubs/gh" <<'STUB'
#!/bin/bash
R=omarchy-asus/omarchy-asus
[[ $1 == api ]] || { echo "unexpected gh $*" >&2; exit 1; }
case $2 in
    repos/$R/actions/runs/*/artifacts\?*) cat "$FX/artifacts.json" ;;
    repos/$R/actions/runs/*) cat "$FX/run.json" ;;
    repos/$R/actions/artifacts/*/zip) cat "$FX/artifact.zip" ;;
    *) echo "unexpected gh api $2" >&2; exit 1 ;;
esac
STUB
chmod +x "$S/stubs/gh" "$S/bin/"* "$S/ci/"*
export PATH=$S/stubs:$PATH FX=$S/fx TMPDIR=$S/tmp RELEASE=file://$S/rel OMARCHY_ASUS_DATA=$S/data
unset OMARCHY_ASUS_CHANNEL GH_TOKEN
fail=0
R=omarchy-asus/omarchy-asus SHA=$(printf 'a%.0s' {1..40})

# tree <dir> <pkgname> <pkgver>: a package's tree, as the chroot builds it
tree() {
    local d=$1 n=$2 v=$3
    rm -rf "$d"; mkdir -p "$d/usr/bin" "$d/etc" "$d/usr/share/$n"
    cat >"$d/.PKGINFO" <<EOF
# Generated by makepkg 7.0.0
pkgname = $n
pkgbase = foo
xdata = pkgtype=split
pkgver = $v
pkgdesc = a test package
url = https://example.invalid/foo
builddate = 1700000000
packager = omarchy-asus
size = 12345
arch = x86_64
license = MIT
depend = glibc
depend = bash
optdepend = python: the helper
provides = $n-cli=$v
conflict = $n-git
replaces = old-$n
backup = etc/$n.conf
EOF
    printf 'post_install() {\n    echo installed\n}\n' >"$d/.INSTALL"
    head -c 4000 /dev/zero >"$d/usr/bin/$n"
    chmod 755 "$d/usr/bin/$n"
    echo "setting=1" >"$d/etc/$n.conf"
    echo "data" >"$d/usr/share/$n/data"
    ln -s "$n" "$d/usr/bin/$n-link"
}
# pack <tree> <out file>
pack() {
    local entries=(.PKGINFO)
    [[ -e $1/.INSTALL ]] && entries+=(.INSTALL)
    bsdtar --zstd --uid 0 --gid 0 --uname root --gname root -cf "$2" -C "$1" "${entries[@]}" usr etc
}
# release <pkgname:ver...>: the channel's release serves these (and bar), signed
release() {
    rm -rf "$S/rel" "$S/db"; mkdir -p "$S/rel" "$S/db"
    local spec n v f
    for spec in "$@" bar:2-1.101; do
        n=${spec%%:*} v=${spec#*:}
        tree "$S/t/$n" "$n" "$v"
        [[ $n == bar ]] && sed -i 's/^pkgbase = foo/pkgbase = bar/' "$S/t/$n/.PKGINFO"
        f=$n-$v-x86_64.pkg.tar.zst
        pack "$S/t/$n" "$S/rel/$f"; sign "$S/rel/$f"
        mkdir -p "$S/db/$n-$v"
        printf '%%FILENAME%%\n%s\n\n%%NAME%%\n%s\n\n%%BASE%%\n%s\n\n%%VERSION%%\n%s\n\n' \
            "$f" "$n" "$( [[ $n == bar ]] && echo bar || echo foo)" "$v" >"$S/db/$n-$v/desc"
    done
    bsdtar -czf "$S/rel/omarchy-asus.db" -C "$S/db" .
    sign "$S/rel/omarchy-asus.db"
}
# artifact: the run's artifact release-rc-foo from the trees in $S/new
artifact() {
    rm -rf "$S/art"; mkdir -p "$S/art"
    local d
    for d in "$S"/new/*/; do
        pack "$d" "$S/art/$(basename "$d")-$(sed -n 's/^pkgver = //p' "$d/.PKGINFO")-x86_64.pkg.tar.zst"
    done
    (cd "$S/art" && sha256sum -- *.pkg.tar.zst >SHA256SUMS)
    rm -f "$FX/artifact.zip"
    (cd "$S/art" && bsdtar --format zip -cf "$FX/artifact.zip" -- *)
    jq -n --arg d "sha256:$(sha256sum <"$FX/artifact.zip" | cut -d' ' -f1)" --arg n "${ART:-release-rc-foo}" \
        '{total_count: 1, artifacts: [{id: 55, name: $n, expired: false, digest: $d}]}' >"$FX/artifacts.json"
}
# new <ver>: the new path's trees, built like the release's
new() {
    rm -rf "$S/new"; mkdir -p "$S/new"
    tree "$S/new/foo" foo "$1"; tree "$S/new/foo-docs" foo-docs "$1"
    # what every build changes: date, packager, compiled contents, a few bytes of size
    sed -i 's/^builddate = .*/builddate = 1800000000/; s/^packager = .*/packager = someone else/' "$S"/new/*/.PKGINFO
    head -c 4010 /dev/urandom >"$S/new/foo/usr/bin/foo"
}
run_json() {
    jq -n --arg r "$R" --arg sha "$SHA" --arg br "${1:-main}" --arg c "${2:-success}" \
        '{id: 900, repository: {full_name: $r}, head_repository: {full_name: $r},
          path: ".github/workflows/release.yml", event: "workflow_dispatch", head_branch: $br,
          status: "completed", conclusion: $c, head_sha: $sha}' >"$FX/run.json"
}

# check <name> <want exit> [text that must appear...]
check() {
    local name=$1 want=$2 got; shift 2
    out=$("$S/bin/compare-build-paths" --channel "${CH:-rc}" foo 900 2>&1); got=$?
    [[ -z ${SHOW:-} ]] || { echo "--- $name"; echo "$out"; }
    if [[ $got != "$want" ]]; then
        echo "FAIL: $name: exit $got, want $want"; echo "$out" | sed 's/^/    /'; fail=1; return
    fi
    local t
    for t in "$@"; do
        grep -qF -- "$t" <<<"$out" || { echo "FAIL: $name: no '$t' in:"; echo "$out" | sed 's/^/    /'; fail=1; return; }
    done
    [[ -z $(ls -A "$S/tmp") ]] || { echo "FAIL: $name: left $(ls "$S/tmp") in TMPDIR"; fail=1; rm -rf "${S:?}"/tmp/*; return; }
    echo "ok: $name"
}

run_json
release foo:1.0-1.101 foo-docs:1.0-1.101

# 1. the same
new 1.0-1.101; artifact
check "identical but for date, packager, contents and size noise" 0 "only expected differences" \
    "1 file(s) differ in size within the threshold" "./usr/bin/foo"
grep -q '^  bar' <<<"$out" && { echo "FAIL: bar, another recipe's package, was compared"; fail=1; }

# 2. differences
new 1.0-1.101; rm "$S/new/foo/usr/share/foo/data"; artifact
check "a dropped file" 1 "files (type, mode, owner, link)" "- ./usr/share/foo/data type=file" "DIFFERS"

new 1.0-1.101; sed -i 's/^depend = bash$/depend = zsh/' "$S/new/foo/.PKGINFO"; artifact
check "a changed dependency" 1 ".PKGINFO fields" "- depend = bash" "+ depend = zsh"

new 1.0-1.101; printf 'post_install() {\n    rm -rf /tmp/x\n}\n' >"$S/new/foo-docs/.INSTALL"; artifact
check "a changed scriptlet" 1 "install scriptlet" "-     echo installed" "+     rm -rf /tmp/x"

new 1.0-1.101; rm "$S/new/foo/.INSTALL"; artifact
check "a dropped scriptlet" 1 "install scriptlet" "+ (no install scriptlet)"

new 1.0-1.101; chmod 4755 "$S/new/foo/usr/bin/foo"; artifact
check "a changed mode" 1 "- ./usr/bin/foo type=file mode=755" "+ ./usr/bin/foo type=file mode=4755"

new 1.0-1.101; head -c 9000 /dev/urandom >"$S/new/foo/usr/bin/foo"; artifact
check "a size beyond the threshold" 1 "file sizes beyond the threshold" "./usr/bin/foo: 4000 -> 9000 bytes (+5000)"

new 1.0-1.101; tree "$S/new/foo-extra" foo-extra 1.0-1.101; artifact
check "a package only the new path builds" 1 "foo-extra: built by the new path only"

new 1.0-1.101; rm -rf "$S/new/foo-docs"; artifact
check "a package only the release serves" 1 "foo-docs: served by the release (1.0-1.101); the new path didn't build it"

# 3. versions
new 1.0-2.101; artifact
check "a version mismatch" 1 "VERSIONS DIFFER" "foo: the release serves 1.0-1.101, the new path built 1.0-2.101" \
    "+ provides = foo-cli=1.0-2.101"
[[ $(grep -n 'VERSIONS DIFFER' <<<"$out" | cut -d: -f1) -lt $(grep -n '^  foo:' <<<"$out" | head -1 | cut -d: -f1) ]] ||
    { echo "FAIL: the version mismatch isn't said first"; fail=1; }

new 1.0-2.101; rm "$S/new/foo/usr/share/foo/data"; artifact
check "a version mismatch still compares the files" 1 "VERSIONS DIFFER" "- ./usr/share/foo/data"

# 4. cannot compare
new 1.0-1.101; artifact
CH=quattro check "the quattro channel" 3 "frozen"
run_json feature; check "a run off main" 3 "branch is 'feature'"
run_json main failure; check "a failed run" 3 "conclusion is 'failure'"
run_json
ART=release-rc-other artifact; check "no artifact for the recipe" 3 "no single artifact named release-rc-foo"
artifact; echo junk >>"$FX/artifact.zip"; check "an artifact whose digest doesn't match" 3 "not the digest GitHub recorded"
artifact; echo junk >>"$S/rel/foo-docs-1.0-1.101-x86_64.pkg.tar.zst"
check "a release package whose signature doesn't verify" 3 "signature does not verify"

exit $fail
